  ASSERT_EQ(0,
            cdd_cst_parse(az_span_create_from_str((char *)(size_t)(size_t)code),
                          &tree));
  cdd_transform_percolate_errors(tree, &config);
  cdd_cst_tree_free(tree);
  tree = NULL;

