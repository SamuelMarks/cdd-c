/**
 * @brief Maps an FFI primitive kind to its corresponding Rust primitive type
 * string.
 *
 * @param[in] kind FFI primitive kind enum value.
 * @param[out] out_type Output pointer receiving the resolved Rust type string.
 * @return `CDD_C_SUCCESS` on success.
 */
static cdd_c_error_t get_rust_primitive(cdd_ffi_primitive_kind_t kind,
                                        const char **out_type) {
  switch (kind) {
  case CDD_FFI_KIND_BOOL:
    *out_type = "bool";
    break;
  case CDD_FFI_KIND_INT8:
    *out_type = "i8";
    break;
  case CDD_FFI_KIND_UINT8:
    *out_type = "u8";
    break;
  case CDD_FFI_KIND_INT16:
    *out_type = "i16";
    break;
  case CDD_FFI_KIND_UINT16:
    *out_type = "u16";
    break;
  case CDD_FFI_KIND_INT32:
    *out_type = "i32";
    break;
  case CDD_FFI_KIND_UINT32:
    *out_type = "u32";
    break;
  case CDD_FFI_KIND_INT64:
    *out_type = "i64";
    break;
  case CDD_FFI_KIND_UINT64:
    *out_type = "u64";
    break;
  case CDD_FFI_KIND_FLOAT32:
    *out_type = "f32";
    break;
  case CDD_FFI_KIND_FLOAT64:
    *out_type = "f64";
    break;
  case CDD_FFI_KIND_OPAQUE_PTR:
    *out_type = "std::ffi::c_void";
    break;
  case CDD_FFI_KIND_FUNCTION_PTR:
    *out_type = "std::ffi::c_void";
    break;
  default:
    *out_type = "std::ffi::c_void";
    break;
  }
  return CDD_C_SUCCESS;
}

/**
 * @brief Writes the Rust raw FFI (`sys`) type representation of an FFI IR type
 * to `f`.
 *
 * @param[in,out] f Output file stream.
 * @param[in] type FFI type descriptor to emit.
 * @param[in] is_return Non-zero if emitting a function return type, 0
 * otherwise.
 * @return `CDD_C_SUCCESS` on success.
 */
static cdd_c_error_t emit_rust_sys_type(FILE *f, const cdd_ffi_type_t *type,
                                        int is_return) {
  const char *prim = NULL;
  if (type->kind == CDD_FFI_KIND_VOID && type->pointer_depth == 0) {
    if (is_return) {
      fprintf(f, "()");
    } else {
      fprintf(f, "std::ffi::c_void");
    }
    return CDD_C_SUCCESS;
  }

  if (type->pointer_depth > 0) {
    cdd_ffi_type_t sub_type;
    int pd;
    for (pd = 0; pd < type->pointer_depth; pd++) {
      if (type->is_const && pd == 0) {
        fprintf(f, "*const ");
      } else {
        fprintf(f, "*mut ");
      }
    }
    sub_type = *type;
    sub_type.pointer_depth = 0;
    sub_type.is_const = 0;
    emit_rust_sys_type(f, &sub_type, 0);
    return CDD_C_SUCCESS;
  }

  if (type->ref_name) {
    fprintf(f, "%s", type->ref_name);
    return CDD_C_SUCCESS;
  }

  get_rust_primitive(type->kind, &prim);
  fprintf(f, "%s", prim);
  return CDD_C_SUCCESS;
}

/**
 * @brief Emits `src/sys.rs` containing `#[repr(C)]` struct definitions and
 * `extern "C"` declarations for the given FFI IR.
 *
 * @param[in] ir The extracted and topologically sorted FFI IR.
 * @param[in] dir_path Output crate root directory path.
 * @return `CDD_C_SUCCESS` on success, or `CDD_C_ERROR_IO` on file failure.
 */
static cdd_c_error_t emit_sys_rs(cdd_ffi_ir_t *ir, const char *dir_path) {
  FILE *f = NULL;
  char filepath[1024];
  size_t i, j;

#if defined(_MSC_VER)
  sprintf_s(filepath, sizeof(filepath), "%s\\src\\sys.rs", dir_path);
  fopen_s(&f, filepath, "w");
#else
  CDD_SNPRINTF(filepath, sizeof(filepath), "%s/src/sys.rs", dir_path);
#if defined(_MSC_VER)
  if (fopen_s(&f, filepath, "w") != 0)
    f = NULL;
#else
  f = fopen(filepath, "w");
#endif
#endif

#ifdef CDD_BUILD_TESTS
  {
    if (g_fail_io_after > 0 && --g_fail_io_after == 0) {
      if (f)
        fclose(f);
      f = NULL;
    }
  }
#endif
  if (!f)
    return CDD_C_ERROR_IO;

  fprintf(f, "/* Auto-generated by cdd-c */\n");
  fprintf(f, "#![allow(non_camel_case_types)]\n");
  fprintf(f, "#![allow(non_snake_case)]\n");
  fprintf(f, "#![allow(dead_code)]\n\n");

  /* Enums, Structs, Typedefs */
  for (i = 0; i < ir->nodes_count; i++) {
    cdd_ffi_ir_node_t *node = &ir->nodes[i];
    if (node->kind == CDD_FFI_NODE_STRUCT || node->kind == CDD_FFI_NODE_UNION) {
      fprintf(f, "#[repr(C)]\n");
      fprintf(f, "#[derive(Debug, Copy, Clone)]\n");
      fprintf(f, "pub %s %s {\n",
              node->kind == CDD_FFI_NODE_UNION ? "union" : "struct",
              node->name);
      for (j = 0; j < node->fields_count; j++) {
        fprintf(f, "    pub %s: ",
                node->fields[j].name ? node->fields[j].name : "field");
        emit_rust_sys_type(f, &node->fields[j].type, 0);
        fprintf(f, ",\n");
      }
      fprintf(f, "}\n\n");
    } else if (node->kind == CDD_FFI_NODE_ENUM) {
      fprintf(f, "pub type %s = std::os::raw::c_int;\n", node->name);
      for (j = 0; j < node->variants_count; j++) {
        fprintf(f, "pub const %s: %s = %s;\n", node->variants[j].name,
                node->name,
                node->variants[j].value ? node->variants[j].value : "0");
      }
      fprintf(f, "\n");
    } else if (node->kind == CDD_FFI_NODE_TYPEDEF) {
      fprintf(f, "pub type %s = ", node->name);
      emit_rust_sys_type(f, &node->return_or_base_type, 0);
      fprintf(f, ";\n\n");
    }
  }

  /* Functions */
  fprintf(f, "extern \"C\" {\n");
  for (i = 0; i < ir->nodes_count; i++) {
    cdd_ffi_ir_node_t *node = &ir->nodes[i];
    if (node->kind == CDD_FFI_NODE_FUNCTION) {
      fprintf(f, "    pub fn %s(", node->name);
      for (j = 0; j < node->fields_count; j++) {
        fprintf(f, "%s: ", node->fields[j].name ? node->fields[j].name : "arg");
        emit_rust_sys_type(f, &node->fields[j].type, 0);
        if (j < node->fields_count - 1)
          fprintf(f, ", ");
      }
      if (node->fields_count > 0)
        fprintf(f, ", ");
      fprintf(f, "err: *mut CddFfiError) -> ");
      emit_rust_sys_type(f, &node->return_or_base_type, 1);
      fprintf(f, ";\n");
    }
  }
  fprintf(f, "}\n");

  fclose(f);
  return CDD_C_SUCCESS;
}

/**
 * @brief Emits `src/lib.rs` containing safe Rust `Result<T, FfiError>` wrappers
 * around `sys` functions.
 *
 * @param[in] ir The extracted and topologically sorted FFI IR.
 * @param[in] dir_path Output crate root directory path.
 * @return `CDD_C_SUCCESS` on success, or `CDD_C_ERROR_IO` on file failure.
 */
static cdd_c_error_t emit_lib_rs(cdd_ffi_ir_t *ir, const char *dir_path) {
  FILE *f = NULL;
  char filepath[1024];
  size_t i;

#if defined(_MSC_VER)
  sprintf_s(filepath, sizeof(filepath), "%s\\src\\lib.rs", dir_path);
  fopen_s(&f, filepath, "w");
#else
  CDD_SNPRINTF(filepath, sizeof(filepath), "%s/src/lib.rs", dir_path);
#if defined(_MSC_VER)
  if (fopen_s(&f, filepath, "w") != 0)
    f = NULL;
#else
  f = fopen(filepath, "w");
#endif
#endif

#ifdef CDD_BUILD_TESTS
  {
    if (g_fail_io_after > 0 && --g_fail_io_after == 0) {
      if (f)
        fclose(f);
      f = NULL;
    }
  }
#endif
  if (!f)
    return CDD_C_ERROR_IO;

  fprintf(f, "/* Auto-generated by cdd-c */\n");
  fprintf(f, "pub mod sys;\n\n");
  fprintf(f, "pub use sys::*;\n\n");

  fprintf(f, "use std::ffi::CStr;\n");
  fprintf(f, "use std::ffi::CString;\n");
  fprintf(f, "use std::os::raw::c_char;\n\n");

  fprintf(f, "#[derive(Debug)]\n");
  fprintf(f, "pub struct FfiError {\n");
  fprintf(f, "    pub code: i32,\n");
  fprintf(f, "    pub message: String,\n");
  fprintf(f, "}\n\n");

  fprintf(f, "impl std::fmt::Display for FfiError {\n");
  fprintf(f, "    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> "
             "std::fmt::Result {\n");
  fprintf(f,
          "        write!(f, \"FfiError({}): {}\", self.code, self.message)\n");
  fprintf(f, "    }\n");
  fprintf(f, "}\n\n");

  fprintf(f, "impl std::error::Error for FfiError {}\n\n");

  /* Safe functions struct wrapper */
  fprintf(f, "pub struct Wrapper;\n\n");
  fprintf(f, "impl Wrapper {\n");
  for (i = 0; i < ir->nodes_count; i++) {
    cdd_ffi_ir_node_t *node = &ir->nodes[i];
    if (node->kind == CDD_FFI_NODE_FUNCTION) {
      size_t j;
      fprintf(f, "    pub fn %s_safe(", node->name);
      for (j = 0; j < node->fields_count; j++) {
        const char *arg_name =
            node->fields[j].name ? node->fields[j].name : "arg";
        fprintf(f, "%s: ", arg_name);
        /* If it's a pointer to i8/u8, use &std::ffi::CStr for idiomatic rust */
        if (node->fields[j].type.pointer_depth == 1 &&
            (node->fields[j].type.kind == CDD_FFI_KIND_INT8 ||
             node->fields[j].type.kind == CDD_FFI_KIND_UINT8)) {
          fprintf(f, "&std::ffi::CStr");
        } else {
          emit_rust_sys_type(f, &node->fields[j].type, 0);
        }
        if (j < node->fields_count - 1)
          fprintf(f, ", ");
      }
      fprintf(f, ") -> Result<");
      emit_rust_sys_type(f, &node->return_or_base_type, 1);
      fprintf(f, ", FfiError> {\n");

      fprintf(f, "        let mut err = sys::CddFfiError {\n");
      fprintf(f, "            code: 0,\n");
      fprintf(f, "            message: std::ptr::null_mut(),\n");
      fprintf(f, "        };\n");

      fprintf(f, "        let res = unsafe { sys::%s(", node->name);
      for (j = 0; j < node->fields_count; j++) {
        const char *arg_name =
            node->fields[j].name ? node->fields[j].name : "arg";
        if (node->fields[j].type.pointer_depth == 1 &&
            (node->fields[j].type.kind == CDD_FFI_KIND_INT8 ||
             node->fields[j].type.kind == CDD_FFI_KIND_UINT8)) {
          fprintf(f, "%s.as_ptr()", arg_name);
        } else {
          fprintf(f, "%s", arg_name);
        }
        fprintf(f, ", ");
      }
      fprintf(f, "&mut err as *mut sys::CddFfiError) };\n");

      fprintf(f, "        if err.code != 0 {\n");
      fprintf(f, "            let msg = if !err.message.is_null() {\n");
      fprintf(f, "                unsafe { CStr::from_ptr(err.message as "
                 "*const c_char).to_string_lossy().into_owned() }\n");
      fprintf(f, "            } else {\n");
      fprintf(f, "                \"Unknown native error\".to_string()\n");
      fprintf(f, "            };\n");
      fprintf(f, "            Err(FfiError { code: err.code as i32, message: "
                 "msg })\n");
      fprintf(f, "        } else {\n");
      fprintf(f, "            Ok(res)\n");
      fprintf(f, "        }\n");

      fprintf(f, "    }\n");
    }
  }
  fprintf(f, "}\n");

  fclose(f);
  return CDD_C_SUCCESS;
}

/**
 * @brief Emits `Cargo.toml` for the generated Rust bindings crate.
 *
 * @param[in] config The bindings generation configuration.
 * @return `CDD_C_SUCCESS` on success, or `CDD_C_ERROR_IO` on file failure.
 */
static cdd_c_error_t
emit_cargo_toml(const cdd_generate_bindings_config_t *config) {
  FILE *f = NULL;
  char filepath[1024];

#if defined(_MSC_VER)
  sprintf_s(filepath, sizeof(filepath), "%s\\Cargo.toml", config->output_dir);
  fopen_s(&f, filepath, "w");
#else
  CDD_SNPRINTF(filepath, sizeof(filepath), "%s/Cargo.toml", config->output_dir);
#if defined(_MSC_VER)
  if (fopen_s(&f, filepath, "w") != 0)
    f = NULL;
#else
  f = fopen(filepath, "w");
#endif
#endif

#ifdef CDD_BUILD_TESTS
  {
    if (g_fail_io_after > 0 && --g_fail_io_after == 0) {
      if (f)
        fclose(f);
      f = NULL;
    }
  }
#endif
  if (!f)
    return CDD_C_ERROR_IO;

  fprintf(f, "[package]\n");
  fprintf(f, "name = \"%s-bindings\"\n",
          (config->library_name) ? config->library_name : "libname");
  fprintf(f, "version = \"0.1.0\"\n");
  fprintf(f, "edition = \"2021\"\n\n");
  fprintf(f, "[dependencies]\n");
  /* if we used libc crate we'd add it here */
  fprintf(f, "libc = \"0.2\"\n");

  fclose(f);
  return CDD_C_SUCCESS;
}

/**
 * @brief Emits `tests/integration_test.rs` containing struct size assertions
 * for the given FFI IR.
 *
 * @param[in] ir The extracted and topologically sorted FFI IR.
 * @param[in] config The bindings generation configuration.
 * @return `CDD_C_SUCCESS` on success, or `CDD_C_ERROR_IO` on file failure.
 */
static cdd_c_error_t
emit_integration_tests(cdd_ffi_ir_t *ir,
                       const cdd_generate_bindings_config_t *config) {
  FILE *f = NULL;
  char filepath[1024];
  size_t i;

#if defined(_MSC_VER)
  sprintf_s(filepath, sizeof(filepath), "%s\\tests\\integration_test.rs",
            config->output_dir);
  fopen_s(&f, filepath, "w");
#else
  CDD_SNPRINTF(filepath, sizeof(filepath), "%s/tests/integration_test.rs",
               config->output_dir);
#if defined(_MSC_VER)
  if (fopen_s(&f, filepath, "w") != 0)
    f = NULL;
#else
  f = fopen(filepath, "w");
#endif
#endif

#ifdef CDD_BUILD_TESTS
  {
    if (g_fail_io_after > 0 && --g_fail_io_after == 0) {
      if (f)
        fclose(f);
      f = NULL;
    }
  }
#endif
  if (!f)
    return CDD_C_ERROR_IO;

  fprintf(f, "use %s_bindings::*;\n\n",
          (config->library_name) ? config->library_name : "libname");
  for (i = 0; i < ir->nodes_count; i++) {
    cdd_ffi_ir_node_t *node = &ir->nodes[i];
    if (node->kind == CDD_FFI_NODE_STRUCT || node->kind == CDD_FFI_NODE_UNION) {
      fprintf(f, "#[test]\n");
      fprintf(f, "fn test_%s_size() {\n", node->name);
      fprintf(f, "    assert!(std::mem::size_of::<%s>() > 0);\n", node->name);
      fprintf(f, "}\n\n");
    }
  }

  fclose(f);
  return CDD_C_SUCCESS;
}

/**
 * @brief Creates a directory at `path`, succeeding if it already exists.
 *
 * @param[in] path Directory path to create.
 * @return `CDD_C_SUCCESS` on success or if `EEXIST`, or an error code on
 * failure.
 */
static cdd_c_error_t maybe_mkdir(const char *path) {
  cdd_c_error_t rc = makedir(path);
  if (rc == CDD_C_SUCCESS)
    return CDD_C_SUCCESS;
  if (errno == EEXIST) {
    return CDD_C_SUCCESS;
  }
  return rc;
}

/**
 * @brief Emits a complete Rust Cargo crate (`Cargo.toml`, `src/sys.rs`,
 * `src/lib.rs`, and optional integration tests) for the given FFI IR.
 *
 * @param[in] ir FFI Intermediate Representation to emit.
 * @param[in] config Binding generation configuration parameters.
 * @return `CDD_C_SUCCESS` on success, or an error code on failure.
 */
cdd_c_error_t cdd_ffi_emit_rust(cdd_ffi_ir_t *ir,
                                const cdd_generate_bindings_config_t *config) {
  cdd_c_error_t rc;
  char src_dir[1024];
  char tests_dir[1024];

  if (!ir || !config || !config->output_dir)
    return CDD_C_ERROR_INVALID_ARGUMENT;

#if defined(_MSC_VER)
  sprintf_s(src_dir, sizeof(src_dir), "%s\\src", config->output_dir);
  sprintf_s(tests_dir, sizeof(tests_dir), "%s\\tests", config->output_dir);
#else
  CDD_SNPRINTF(src_dir, sizeof(src_dir), "%s/src", config->output_dir);
  CDD_SNPRINTF(tests_dir, sizeof(tests_dir), "%s/tests", config->output_dir);
#endif

  {
    cdd_c_error_t rc_rs = maybe_mkdir(src_dir);
    if (rc_rs != CDD_C_SUCCESS)
      return rc_rs;
  }
  {
    cdd_c_error_t rc_rs = maybe_mkdir(tests_dir);
#ifdef CDD_BUILD_TESTS
    if (g_fail_io_after == 557)
      rc_rs = CDD_C_ERROR_UNKNOWN;
#endif
    if (rc_rs != CDD_C_SUCCESS)
      return rc_rs;
  }

  rc = emit_cargo_toml(config);
  /* In tests we don't mock emit_sys_rs failing inside cdd_ffi_emit_rust if it
   * already fails within emit_sys_rs */
  if (rc != CDD_C_SUCCESS)
    return rc;

  rc = emit_sys_rs(ir, config->output_dir);
  if (rc != CDD_C_SUCCESS)
    return rc;

  rc = emit_lib_rs(ir, config->output_dir);
  if (rc != CDD_C_SUCCESS)
    return rc;

  if (config->generate_tests) {
    rc = emit_integration_tests(ir, config);
    if (rc != CDD_C_SUCCESS)
      return rc;
  }

  return CDD_C_SUCCESS;
}
