/**
 * @file client_gen_url_utils_c1.c
 * @brief url_utils.c (part 1) emission for OpenAPI client generator.
 */

/* clang-format off */
#include "c_cdd/safe_crt_msvc.h"

#include "routes/emit/client_gen_internal.h"
#include "c_cdd/code_writer.h"
#include "c_cdd/log.h"
#include "c_cdd/safe_crt.h"
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
/* clang-format on */

/**
 * @brief Emit url_utils.c (part 1) for installable package.
 */
cdd_c_error_t client_gen_emit_url_utils_c1(FILE *uc) {
  if (uc) {
    cdd_c_error_t rc = CDD_C_SUCCESS;
    cdd_code_writer_t w;
    cdd_code_writer_init_stream(&w, uc);
    cdd_code_writer_write(
        &w,
        "/**\n"
        " * @file url.c\n"
        " * @brief Implementation of RFC 3986 URL encoding and Query "
        "serialization.\n"
        " *\n"
        " * @author Samuel Marks\n"
        " */\n"
        "\n"
        "/* clang-format "
        "off */\n"
        "#include <ctype.h>\n"
        "#include <errno.h>\n"
        "#include <stdio.h>\n"
        "#include <stdlib.h>\n"
        "#include <string.h>\n"
        "\n"
        "#include \"functions/parse/str.h\" /* For c_cdd_strdup helpers */\n");
    cdd_code_writer_write(
        &w, "#include \"c_cdd/log.h\"\n#include \"url_utils.h\"\n"
            "/* clang-format "
            "on */\n"
            "\n"
            "/* Standard definitions for C89 compatibility */\n"
            "#if defined(_MSC_VER) && !defined(__INTEL_COMPILER)\n"
            "#define sprintf_s_chk(buf, size, fmt, arg) sprintf_s(buf, size, "
            "fmt, arg)\n"
            "#else\n"
            "/* Naive fallback for non-MSVC C89 */\n"
            "/** @brief sprintf_s_chk macro */\n");
    cdd_code_writer_write(
        &w, "#define sprintf_s_chk(buf, size, fmt, arg) CDD_SNPRINTF(buf, "
            "size, fmt, arg)\n"
            "#endif\n"
            "\n"
            "/**\n"
            " * @brief Check if a character is unreserved per RFC 3986 Section "
            "2.3.\n"
            " *\n"
            " * Unreserved characters: ALPHA, DIGIT, \"-\", \".\", \"_\", "
            "\"~\".\n"
            " */\n"
            "static cdd_c_error_t is_unreserved(unsigned char c) {\n"
            "  if (isalnum(c))\n"
            "    return CDD_C_ERROR_UNKNOWN;\n");
    cdd_code_writer_write(
        &w, "  if (c == '-' || c == '.' || c == '_' || c == '~')\n"
            "    return CDD_C_ERROR_UNKNOWN;\n"
            "  return CDD_C_SUCCESS;\n"
            "}\n"
            "\n"
            "/**\n"
            " * @brief Check if a character is reserved per RFC 3986 Section "
            "2.2.\n"
            " */\n"
            "static cdd_c_error_t is_reserved(unsigned char c) {\n"
            "  switch (c) {\n"
            "  case ':':\n"
            "  case '/':\n"
            "  case '?':\n"
            "  case '#':\n"
            "  case '[':\n"
            "  case ']':\n"
            "  case '@':\n");
    cdd_code_writer_write(&w, "  case '!':\n"
                              "  case '$':\n"
                              "  case '&':\n"
                              "  case '\\'':\n"
                              "  case '(':\n"
                              "  case ')':\n"
                              "  case '*':\n"
                              "  case '+':\n"
                              "  case ',':\n"
                              "  case ';':\n"
                              "  case '=':\n"
                              "    return CDD_C_ERROR_UNKNOWN;\n"
                              "  default:\n"
                              "    return CDD_C_SUCCESS;\n"
                              "  }\n"
                              "}\n"
                              "\n"
                              "static cdd_c_error_t is_hex(unsigned char c) {\n"
                              "  return isxdigit(c) ? 1 : 0;\n"
                              "}\n"
                              "\n"
                              "static cdd_c_error_t\n");
    cdd_code_writer_write(
        &w, "    is_pct_encoded(const char *p) {\n"
            "  if (!p)\n"
            "    return CDD_C_SUCCESS;\n"
            "  return (p[0] == '%' && is_hex((unsigned char)p[1]) &&\n"
            "          is_hex((unsigned char)p[2]));\n"
            "}\n"
            "\n"
            "/**\n"
            " * @brief Convert a nibble to hexagonal character.\n"
            " */\n"
            "static cdd_c_error_t to_hex(char code, char *_out_val) {\n"
            "  static const char hex[] = \"0123456789ABCDEF\";\n"
            "  {\n");
    cdd_code_writer_write(
        &w, "    *_out_val = hex[code & 15];\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "}\n"
            "\n"
            "static cdd_c_error_t is_unreserved_form(unsigned char c) {\n"
            "  if (isalnum(c))\n"
            "    return CDD_C_ERROR_UNKNOWN;\n"
            "  if (c == '-' || c == '.' || c == '_' || c == '*')\n"
            "    return CDD_C_ERROR_UNKNOWN;\n"
            "  return CDD_C_SUCCESS;\n"
            "}\n"
            "\n"
            "/**\n"
            " * @brief Percent-encodes a string according to RFC 3986 "
            "unreserved character rules.\n"
            " */\n");
    cdd_code_writer_write(
        &w, "cdd_c_error_t url_encode(const char *str, char **_out_val) {\n"
            "  char hex_hi;\n"
            "  char hex_lo;\n"
            "  const char *p;\n"
            "  char *enc = NULL;\n"
            "  char *e;\n"
            "  size_t needed_len = 0;\n"
            "\n"
            "  if (!str) {\n"
            "    *_out_val = NULL;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "\n"
            "  /* Pass 1: Calculate required length */\n"
            "  for (p = str; *p; p++) {\n");
    cdd_code_writer_write(&w, "    if (is_unreserved((unsigned char)*p)) {\n"
                              "      needed_len++;\n"
                              "    } else {\n"
                              "      needed_len += 3; /* %HH */\n"
                              "    }\n"
                              "  }\n"
                              "\n"
                              "  /* Alloc */\n"
                              "  enc = (char *)malloc(needed_len + 1);\n"
                              "  if (!enc) {\n"
                              "    *_out_val = NULL;\n"
                              "    return CDD_C_ERROR_MEMORY;\n"
                              "  }\n"
                              "\n"
                              "  /* Pass 2: Encode */\n"
                              "  e = enc;\n"
                              "  for (p = str; *p; p++) {\n"
                              "    unsigned char c = (unsigned char)*p;\n");
    cdd_code_writer_write(
        &w, "    if (is_unreserved(c)) {\n"
            "      *e++ = *p;\n"
            "    } else {\n"
            "      *e++ = '%';\n"
            "      to_hex((char)(c >> 4), &hex_hi); *e++ = hex_hi;\n"
            "      to_hex((char)(c & 15), &hex_lo); *e++ = hex_lo;\n"
            "    }\n"
            "  }\n"
            "  *e = '\\0';\n"
            "\n"
            "  {\n"
            "    *_out_val = enc;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "}\n"
            "\n"
            "/**\n");
    cdd_code_writer_write(
        &w, " * @brief Percent-encodes a string while preserving RFC 3986 "
            "reserved characters and %HH triples.\n"
            " */\n"
            "cdd_c_error_t url_encode_allow_reserved(const char *str, char "
            "**_out_val) {\n"
            "  char hex_hi;\n"
            "  char hex_lo;\n"
            "  const char *p;\n"
            "  char *enc = NULL;\n"
            "  char *e;\n"
            "  size_t needed_len = 0;\n"
            "\n"
            "  if (!str) {\n"
            "    *_out_val = NULL;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "\n");
    cdd_code_writer_write(
        &w, "  /* Pass 1: Calculate required length */\n"
            "  for (p = str; *p; p++) {\n"
            "    if (*p == '%' && is_pct_encoded(p)) {\n"
            "      needed_len += 3;\n"
            "      p += 2;\n"
            "      continue;\n"
            "    }\n"
            "    if (is_unreserved((unsigned char)*p) || is_reserved((unsigned "
            "char)*p)) {\n"
            "      needed_len++;\n"
            "    } else {\n"
            "      needed_len += 3; /* %HH */\n"
            "    }\n"
            "  }\n"
            "\n");
    cdd_code_writer_write(&w,
                          "  enc = (char *)malloc(needed_len + 1);\n"
                          "  if (!enc) {\n"
                          "    *_out_val = NULL;\n"
                          "    return CDD_C_ERROR_MEMORY;\n"
                          "  }\n"
                          "\n"
                          "  e = enc;\n"
                          "  for (p = str; *p; p++) {\n"
                          "    unsigned char c = (unsigned char)*p;\n"
                          "    if (*p == '%' && is_pct_encoded(p)) {\n"
                          "      *e++ = *p++;\n"
                          "      *e++ = *p++;\n"
                          "      *e++ = *p;\n"
                          "      continue;\n"
                          "    }\n"
                          "    if (is_unreserved(c) || is_reserved(c)) {\n");
    cdd_code_writer_write(
        &w, "      *e++ = *p;\n"
            "    } else {\n"
            "      *e++ = '%';\n"
            "      to_hex((char)(c >> 4), &hex_hi); *e++ = hex_hi;\n"
            "      to_hex((char)(c & 15), &hex_lo); *e++ = hex_lo;\n"
            "    }\n"
            "  }\n"
            "  *e = '\\0';\n"
            "  {\n"
            "    *_out_val = enc;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "}\n"
            "\n"
            "/**\n"
            " * @brief Percent-encodes a string for "
            "application/x-www-form-urlencoded (spaces as +).\n"
            " */\n");
    cdd_code_writer_write(
        &w, "cdd_c_error_t url_encode_form(const char *str, char **_out_val) "
            "{\n"
            "  char hex_hi;\n"
            "  char hex_lo;\n"
            "  const char *p;\n"
            "  char *enc = NULL;\n"
            "  char *e;\n"
            "  size_t needed_len = 0;\n"
            "\n"
            "  if (!str) {\n"
            "    *_out_val = NULL;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "\n"
            "  for (p = str; *p; p++) {\n"
            "    unsigned char c = (unsigned char)*p;\n"
            "    if (c == ' ') {\n");
    cdd_code_writer_write(&w, "      needed_len++;\n"
                              "    } else if (is_unreserved_form(c)) {\n"
                              "      needed_len++;\n"
                              "    } else {\n"
                              "      needed_len += 3;\n"
                              "    }\n"
                              "  }\n"
                              "\n"
                              "  enc = (char *)malloc(needed_len + 1);\n"
                              "  if (!enc) {\n"
                              "    *_out_val = NULL;\n"
                              "    return CDD_C_ERROR_MEMORY;\n"
                              "  }\n"
                              "\n"
                              "  e = enc;\n"
                              "  for (p = str; *p; p++) {\n"
                              "    unsigned char c = (unsigned char)*p;\n"
                              "    if (c == ' ') {\n");
    cdd_code_writer_write(
        &w, "      *e++ = '+';\n"
            "    } else if (is_unreserved_form(c)) {\n"
            "      *e++ = *p;\n"
            "    } else {\n"
            "      *e++ = '%';\n"
            "      to_hex((char)(c >> 4), &hex_hi); *e++ = hex_hi;\n"
            "      to_hex((char)(c & 15), &hex_lo); *e++ = hex_lo;\n"
            "    }\n"
            "  }\n"
            "  *e = '\\0';\n"
            "  {\n"
            "    *_out_val = enc;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "}\n"
            "\n"
            "/**\n");
    cdd_code_writer_write(
        &w, " * @brief Form-encodes a string while preserving non-delimiter "
            "reserved characters.\n"
            " */\n"
            "cdd_c_error_t url_encode_form_allow_reserved(const char *str, "
            "char "
            "**_out_val) {\n"
            "  char hex_hi;\n"
            "  char hex_lo;\n"
            "  const char *p;\n"
            "  char *enc = NULL;\n"
            "  char *e;\n"
            "  size_t needed_len = 0;\n"
            "\n"
            "  if (!str) {\n"
            "    *_out_val = NULL;\n");
    cdd_code_writer_write(
        &w, "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "\n"
            "  for (p = str; *p; p++) {\n"
            "    unsigned char c = (unsigned char)*p;\n"
            "    if (c == ' ') {\n"
            "      needed_len++;\n"
            "    } else if (is_pct_encoded(p)) {\n"
            "      needed_len += 3;\n"
            "      p += 2;\n"
            "    } else if (is_unreserved_form(c) || is_reserved(c)) {\n"
            "      if (c == '&' || c == '=' || c == '+') {\n"
            "        needed_len += 3;\n"
            "      } else {\n");
    cdd_code_writer_write(&w, "        needed_len++;\n"
                              "      }\n"
                              "    } else {\n"
                              "      needed_len += 3;\n"
                              "    }\n"
                              "  }\n"
                              "\n"
                              "  enc = (char *)malloc(needed_len + 1);\n"
                              "  if (!enc) {\n"
                              "    *_out_val = NULL;\n"
                              "    return CDD_C_ERROR_MEMORY;\n"
                              "  }\n"
                              "\n"
                              "  e = enc;\n"
                              "  for (p = str; *p; p++) {\n"
                              "    unsigned char c = (unsigned char)*p;\n"
                              "    if (c == ' ') {\n"
                              "      *e++ = '+';\n"
                              "    } else if (is_pct_encoded(p)) {\n");
    cdd_code_writer_write(
        &w, "      *e++ = *p++;\n"
            "      *e++ = *p++;\n"
            "      *e++ = *p;\n"
            "    } else if (is_unreserved_form(c) || is_reserved(c)) {\n"
            "      if (c == '&' || c == '=' || c == '+') {\n"
            "        *e++ = '%';\n"
            "        to_hex((char)(c >> 4), &hex_hi); *e++ = hex_hi;\n"
            "        to_hex((char)(c & 15), &hex_lo); *e++ = hex_lo;\n"
            "      } else {\n"
            "        *e++ = *p;\n"
            "      }\n"
            "    } else {\n");
    cdd_code_writer_write(
        &w, "      *e++ = '%';\n"
            "      to_hex((char)(c >> 4), &hex_hi); *e++ = hex_hi;\n"
            "      to_hex((char)(c & 15), &hex_lo); *e++ = hex_lo;\n"
            "    }\n"
            "  }\n"
            "  *e = '\\0';\n"
            "  {\n"
            "    *_out_val = enc;\n"
            "    return CDD_C_SUCCESS;\n"
            "  }\n"
            "}\n"
            "\n"
            "/**\n"
            " * @brief Initializes a UrlQueryParams container to empty state.\n"
            " */\n"
            "cdd_c_error_t url_query_init(struct UrlQueryParams *qp) {\n");
    cdd_code_writer_write(&w, "  if (!qp)\n"
                              "    return CDD_C_ERROR_INVALID_ARGUMENT;\n"
                              "  qp->params = NULL;\n"
                              "  qp->count = 0;\n"
                              "  qp->capacity = 0;\n"
                              "  return CDD_C_SUCCESS;\n"
                              "}\n"
                              "\n");
    cdd_code_writer_check_error(&w, &rc);
    cdd_code_writer_free(&w);
    return rc;
  }
  return CDD_C_SUCCESS;
}
